let lang = null;

export function getLang() {
  if (lang) return lang;
  const saved = localStorage.getItem('ep-lang');
  if (saved && dict[saved]) {
    lang = saved;
  } else {
    const nav = (navigator.language || 'en').slice(0, 2);
    lang = dict[nav] ? nav : 'en';
  }
  return lang;
}

export function setLang(code) {
  if (!dict[code]) return;
  lang = code;
  localStorage.setItem('ep-lang', code);
  document.documentElement.lang = code;
  window.dispatchEvent(new CustomEvent('ep-langchange', { detail: code }));
}

/** Translate a key, with {var} interpolation. Falls back to English, then the key. */
export function t(key, vars = {}) {
  const langDict = dict[getLang()] || dict.en;
  let str = langDict[key] ?? dict.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    str = str.replaceAll(`{${name}}`, value);
  }
  return str;
}

/** Build a <select> for switching language; call once per page. */
export function languagePicker(onChange) {
  const select = document.createElement('select');
  select.className = 'input lang-picker';
  select.setAttribute('aria-label', t('common.language'));
  for (const { code, label } of LANGUAGES) {
    const opt = document.createElement('option');
    opt.value = code;
    opt.textContent = label;
    opt.selected = code === getLang();
    select.appendChild(opt);
  }
  select.addEventListener('change', () => {
    setLang(select.value);
    if (onChange) onChange(select.value);
  });
  return select;
}
